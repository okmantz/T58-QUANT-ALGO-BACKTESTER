_MQL5_KIND_INFO = {
    "sma": ("iMA", "MODE_SMA"), "ema": ("iMA", "MODE_EMA"), "wma": ("iMA", "MODE_LWMA"),
    "rsi": ("iRSI", None), "atr": ("iATR", None), "adx": ("iADX", None),
}


def _mql5_price_call(field_name: str, shift: str) -> str:
    fn = {"open": "iOpen", "high": "iHigh", "low": "iLow", "close": "iClose"}.get(field_name, "iClose")
    return f"{fn}(_Symbol, PERIOD_CURRENT, {shift})"


def _mql5_price_const(field_name: str) -> str:
    """ENUM_APPLIED_PRICE token for a config field; anything that isn't a
    price (e.g. a MACD sourced on volume) falls back to PRICE_CLOSE --
    MQL5 has no volume applied price."""
    return f"PRICE_{field_name.upper()}" if field_name in ("open", "high", "low", "close") else "PRICE_CLOSE"


def _mql5_declare_indicators(indicators: dict[tuple, _Operand]) -> tuple[list[str], list[str], list[str], dict[tuple, str]]:
    """Returns (global declarations, OnInit handle-creation lines,
    OnTick CopyBuffer lines, {operand_key: array_variable_name})."""
    globals_: list[str] = []
    init_lines: list[str] = []
    tick_lines: list[str] = []
    var_map: dict[tuple, str] = {}

    # MACD (fixed 12/26/9): one iMACD handle per source field, one buffer
    # per output line. Registration goes through op.key() -- keying by the
    # old fixed ("macd", field, 0) tuples crashed with a KeyError on any
    # MACD operand whose config carried a period.
    macd_fields = sorted({op.field for op in indicators.values() if op.kind in ("macd", "macd_signal", "macd_histogram")})
    for fld in macd_fields:
        handle = f"h_macd_{fld}"
        globals_.append(f"int {handle};")
        init_lines.append(f'{handle} = iMACD(_Symbol, PERIOD_CURRENT, 12, 26, 9, {_mql5_price_const(fld)});')
        for buf_idx, kind in ((0, "macd"), (1, "macd_signal"), (2, "macd_histogram")):
            arr = f"{handle}_buf{buf_idx}"
            globals_.append(f"double {arr}[];")
            tick_lines.append(f"ArraySetAsSeries({arr}, true);")
            tick_lines.append(f"CopyBuffer({handle}, {buf_idx}, 0, 3, {arr});")
            for op in indicators.values():
                if op.kind == kind and op.field == fld:
                    var_map[op.key()] = arr

    bb_groups = sorted({(op.field, op.period) for op in indicators.values()
                         if op.kind in ("bollinger_mid", "bollinger_upper", "bollinger_lower")})
    for fld, period in bb_groups:
        handle = f"h_bb_{fld}_{period}"
        globals_.append(f"int {handle};")
        init_lines.append(f'{handle} = iBands(_Symbol, PERIOD_CURRENT, {period}, 0, 2.0, {_mql5_price_const(fld)});')
        for buf_idx, kind in ((0, "bollinger_mid"), (1, "bollinger_upper"), (2, "bollinger_lower")):
            arr = f"{handle}_buf{buf_idx}"
            globals_.append(f"double {arr}[];")
            tick_lines.append(f"ArraySetAsSeries({arr}, true);")
            tick_lines.append(f"CopyBuffer({handle}, {buf_idx}, 0, 3, {arr});")
            for op in indicators.values():
                if op.kind == kind and op.field == fld and op.period == period:
                    var_map[op.key()] = arr

    # Kinds rendered inline in _mql5_render_scalar (price formulas or the
    # T58* helpers emitted by to_mql5) need no indicator handle at all.
    _inline_kinds = (
        {"candle_direction", "highest_high", "lowest_low", "vwap",
         "vwma", "average_volume", "candle_range", "percentage_change"}
        | _DONCHIAN_KINDS | _ADVANCED_BOOL_KINDS | _REGIME_KINDS | _SESSION_KINDS
    )
    for key, op in indicators.items():
        if op.kind in ("macd", "macd_signal", "macd_histogram", "bollinger_mid", "bollinger_upper", "bollinger_lower"):
            continue
        if op.kind in _inline_kinds:
            continue
        fn, mode = _MQL5_KIND_INFO[op.kind]
        handle = f"h_{op.kind}_{op.period}_{op.field}"
        arr = f"{handle}_buf"
        globals_.append(f"int {handle};")
        globals_.append(f"double {arr}[];")
        if fn == "iMA":
            init_lines.append(f'{handle} = iMA(_Symbol, PERIOD_CURRENT, {op.period}, 0, {mode}, {_mql5_price_const(op.field)});')
        elif fn == "iRSI":
            init_lines.append(f'{handle} = iRSI(_Symbol, PERIOD_CURRENT, {op.period}, {_mql5_price_const(op.field)});')
        elif fn == "iADX":
            init_lines.append(f'{handle} = iADX(_Symbol, PERIOD_CURRENT, {op.period});')
        elif fn == "iATR":
            init_lines.append(f'{handle} = iATR(_Symbol, PERIOD_CURRENT, {op.period});')
        tick_lines.append(f"ArraySetAsSeries({arr}, true);")
        tick_lines.append(f"CopyBuffer({handle}, 0, 0, 3, {arr});")
        var_map[key] = arr

    missing = [op.kind for op in indicators.values()
               if op.kind not in _inline_kinds and op.key() not in var_map]
    if missing:  # pragma: no cover -- every supported kind resolves above
        raise TranslationError(f"Unhandled indicator kind(s) during MQL5 generation: {sorted(set(missing))}.")
    return globals_, init_lines, tick_lines, var_map


def _mql5_prior_extremes(window: int, shift: str) -> tuple[str, str]:
    """(prior highest high, prior lowest low) over the `window` bars
    BEFORE the bar at `shift` -- the engine's shift(1)-then-roll window."""
    hi = f"iHigh(_Symbol, PERIOD_CURRENT, iHighest(_Symbol, PERIOD_CURRENT, MODE_HIGH, {window}, ({shift}) + 1))"
    lo = f"iLow(_Symbol, PERIOD_CURRENT, iLowest(_Symbol, PERIOD_CURRENT, MODE_LOW, {window}, ({shift}) + 1))"
    return hi, lo


def _mql5_bool_expr(op: _Operand, shift: str) -> str:
    """Inline 1.0/0.0 expression for the advanced boolean kinds,
    mirroring app.strategy.manual._advanced_boolean (same windows,
    direction filter, confirmation shift)."""
    s = int(shift)
    w = op.window
    d = op.direction
    close = _mql5_price_call("close", shift)
    open_ = _mql5_price_call("open", shift)
    if op.kind == "swing_high":
        return f"(T58IsSwing({w}, {s}, true) ? 1.0 : 0.0)"
    if op.kind == "swing_low":
        return f"(T58IsSwing({w}, {s}, false) ? 1.0 : 0.0)"
    prior_hi, prior_lo = _mql5_prior_extremes(w, shift)
    if op.kind == "bos":
        bull = f"({close} > {prior_hi})"
        bear = f"({close} < {prior_lo})"
    elif op.kind == "liquidity_sweep":
        low, high = _mql5_price_call("low", shift), _mql5_price_call("high", shift)
        bull = f"(({low} < {prior_lo}) && ({close} > {prior_lo}))"
        bear = f"(({high} > {prior_hi}) && ({close} < {prior_hi}))"
    elif op.kind == "choch":
        high_w, low_w = _mql5_price_call("high", str(s + w)), _mql5_price_call("low", str(s + w))
        low_1, high_1 = _mql5_price_call("low", str(s + 1)), _mql5_price_call("high", str(s + 1))
        low_w1, high_w1 = _mql5_price_call("low", str(s + w + 1)), _mql5_price_call("high", str(s + w + 1))
        bull = f"(({close} > {high_w}) && ({low_1} < {low_w1}))"
        bear = f"(({close} < {low_w}) && ({high_1} > {high_w1}))"
    elif op.kind == "fvg":
        low, high = _mql5_price_call("low", shift), _mql5_price_call("high", shift)
        bull = f"({low} > {_mql5_price_call('high', str(s + 2))})"
        bear = f"({high} < {_mql5_price_call('low', str(s + 2))})"
    elif op.kind == "order_block":
        close_1, open_1 = _mql5_price_call("close", str(s + 1)), _mql5_price_call("open", str(s + 1))
        high_1, low_1 = _mql5_price_call("high", str(s + 1)), _mql5_price_call("low", str(s + 1))
        bull = f"(({close_1} < {open_1}) && ({close} > {high_1} + T58RangeMean({w}, {s})))"
        bear = f"(({close_1} > {open_1}) && ({close} < {low_1} - T58RangeMean({w}, {s})))"
    else:  # pragma: no cover -- guarded by caller
        raise TranslationError(f"Unhandled boolean kind '{op.kind}' during MQL5 generation.")
    if d == "bullish":
        return f"({bull} ? 1.0 : 0.0)"
    if d == "bearish":
        return f"({bear} ? 1.0 : 0.0)"
    return f"(({bull} || {bear}) ? 1.0 : 0.0)"


def _mql5_regime_expr(op: _Operand, shift: str) -> str:
    p, exp_m, cont_m = op.period, _fmt_num(op.expansion_mult), _fmt_num(op.contraction_mult)
    if op.kind in ("atr_regime", "atr_expansion", "atr_contraction"):
        base = f"T58AtrRegime({p}, {exp_m}, {cont_m}, {shift})"
    else:
        base = f"T58VolRegime({p}, {exp_m}, {cont_m}, {shift})"
    if op.kind == "atr_expansion":
        return f"({base} == 1 ? 1.0 : 0.0)"
    if op.kind == "atr_contraction":
        return f"({base} == -1 ? 1.0 : 0.0)"
    return base


def _mql5_session_expr(op: _Operand, shift: str) -> str:
    s_min, e_min = _pine_session_minutes(op.session_start), _pine_session_minutes(op.session_end)
    if op.kind == "previous_day_high":
        return "iHigh(_Symbol, PERIOD_D1, 1)"
    if op.kind == "previous_day_low":
        return "iLow(_Symbol, PERIOD_D1, 1)"
    if op.kind == "previous_day_close":
        return "iClose(_Symbol, PERIOD_D1, 1)"
    if op.kind == "session_high":
        return f"T58SessionExtreme({shift}, {s_min}, {e_min}, true)"
    if op.kind == "session_low":
        return f"T58SessionExtreme({shift}, {s_min}, {e_min}, false)"
    if op.kind == "opening_range_high":
        return f"T58OpeningRange({shift}, {s_min}, {e_min}, true)"
    if op.kind == "opening_range_low":
        return f"T58OpeningRange({shift}, {s_min}, {e_min}, false)"
    if op.kind == "time_of_day":
        return f"((T58MinutesOfDay({shift}) >= {s_min} && T58MinutesOfDay({shift}) <= {e_min}) ? 1.0 : 0.0)"
    if op.kind == "day_of_week":
        if op.days:
            cond = " || ".join(f"T58DayOfWeek({shift}) == {d}" for d in op.days)
            return f"(({cond}) ? 1.0 : 0.0)"
        return f"T58DayOfWeek({shift})"
    raise TranslationError(f"Unhandled session kind '{op.kind}' during MQL5 generation.")  # pragma: no cover


def _mql5_render_scalar(op: _Operand, var_map: dict[tuple, str], shift: str = "0") -> str:
    """Renders op's value at `shift` (0 = current/most recent closed bar, 1 = prior)."""
    if op.kind == "constant":
        return _fmt_num(op.value)
    if op.kind == "price":
        return _mql5_price_call(op.field, shift)
    if op.kind == "candle_direction":
        c, o = _mql5_price_call("close", shift), _mql5_price_call("open", shift)
        if op.direction == "bullish":
            return f"({c} > {o} ? 1 : 0)"
        if op.direction == "bearish":
            return f"({c} < {o} ? 1 : 0)"
        return f"({c} > {o} ? 1 : ({c} < {o} ? -1 : 0))"
    if op.kind == "highest_high":
        return f"iHigh(_Symbol, PERIOD_CURRENT, iHighest(_Symbol, PERIOD_CURRENT, MODE_HIGH, {op.period}, {shift}))"
    if op.kind == "lowest_low":
        return f"iLow(_Symbol, PERIOD_CURRENT, iLowest(_Symbol, PERIOD_CURRENT, MODE_LOW, {op.period}, {shift}))"
    if op.kind == "vwap":
        return f"ComputeVWAP({shift})"
    if op.kind == "vwma":
        field_code = {"open": 0, "high": 1, "low": 2, "close": 3}.get(op.field, 3)
        return f"T58VWMA({op.period}, {shift}, {field_code})"
    if op.kind == "average_volume":
        return f"T58AvgVolume({op.period}, {shift})"
    if op.kind == "candle_range":
        return f"({_mql5_price_call('high', shift)} - {_mql5_price_call('low', shift)})"
    if op.kind == "percentage_change":
        cur, prev = _mql5_price_call(op.field, shift), _mql5_price_call(op.field, str(int(shift) + op.period))
        return f"(({cur} / {prev} - 1.0) * 100.0)"
    if op.kind in _DONCHIAN_KINDS:
        up, lo = _mql5_prior_extremes(op.period, shift)
        if op.kind == "donchian_upper":
            return up
        if op.kind == "donchian_lower":
            return lo
        return f"(({up} + {lo}) / 2.0)"
    if op.kind in ("bos", "choch", "liquidity_sweep", "fvg", "order_block", "swing_high", "swing_low"):
        return _mql5_bool_expr(op, shift)
    if op.kind in ("swing_bos", "swing_choch"):
        return f"T58SwingEvent({op.window}, {shift}, {1 if op.kind == 'swing_choch' else 0})"
    if op.kind in _REGIME_KINDS:
        return _mql5_regime_expr(op, shift)
    if op.kind in _SESSION_KINDS:
        return _mql5_session_expr(op, shift)
    return f"{var_map[op.key()]}[{shift}]"


def _mql5_helper_lines(indicators: dict[tuple, _Operand]) -> list[str]:
    """T58* helper function bodies, emitted only for the kinds a given
    strategy actually uses. Each is a closed-form port of the engine's
    own series math (see app.strategy.manual / app.strategy.indicators)
    so the generated EA computes the same numbers the backtester did."""
    kinds = {op.kind for op in indicators.values()}
    lines: list[str] = []
    if not (kinds & ({"vwma", "average_volume", "order_block", "swing_high", "swing_low",
                      "swing_bos", "swing_choch"} | _REGIME_KINDS | _SESSION_KINDS)):
        return lines
    lines += [
        "",
        "// --- T58 translator helpers (ports of the engine's series math) ---",
    ]
    if "vwma" in kinds:
        lines += [
            "double T58PriceAt(int fieldCode, int shift)",
            "{",
            "   if(fieldCode == 0) return iOpen(_Symbol, PERIOD_CURRENT, shift);",
            "   if(fieldCode == 1) return iHigh(_Symbol, PERIOD_CURRENT, shift);",
            "   if(fieldCode == 2) return iLow(_Symbol, PERIOD_CURRENT, shift);",
            "   return iClose(_Symbol, PERIOD_CURRENT, shift);",
            "}",
            "",
            "double T58VWMA(int period, int shift, int priceField)",
            "{",
            "   double sumPV = 0.0, sumV = 0.0;",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   for(int i = shift; i < shift + period && i < total; i++)",
            "   {",
            "      double vol = (double)iVolume(_Symbol, PERIOD_CURRENT, i);",
            "      sumPV += T58PriceAt(priceField, i) * vol;",
            "      sumV += vol;",
            "   }",
            "   return sumV > 0.0 ? sumPV / sumV : T58PriceAt(priceField, shift);",
            "}",
            "",
        ]
    if "average_volume" in kinds:
        lines += [
            "double T58AvgVolume(int period, int shift)",
            "{",
            "   double sum = 0.0;",
            "   int n = 0, total = Bars(_Symbol, PERIOD_CURRENT);",
            "   for(int i = shift; i < shift + period && i < total; i++) { sum += (double)iVolume(_Symbol, PERIOD_CURRENT, i); n++; }",
            "   return n > 0 ? sum / n : 0.0;",
            "}",
            "",
        ]
    if "order_block" in kinds:
        lines += [
            "double T58RangeMean(int len, int shift)",
            "{",
            "   double sum = 0.0;",
            "   int n = 0, total = Bars(_Symbol, PERIOD_CURRENT);",
            "   for(int i = shift; i < shift + len && i < total; i++) { sum += iHigh(_Symbol, PERIOD_CURRENT, i) - iLow(_Symbol, PERIOD_CURRENT, i); n++; }",
            "   return n > 0 ? sum / n : 0.0;",
            "}",
            "",
        ]
    if kinds & {"swing_high", "swing_low"}:
        lines += [
            "bool T58IsSwing(int w, int shift, bool wantHigh)",
            "{",
            "   // Confirmed-swing flag: the bar `w` bars before `shift` was the extreme of",
            "   // its centered window (ties allowed, matching manual.py's swing operands).",
            "   int c = shift + w;",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   if(c + w >= total) return false;",
            "   double v = wantHigh ? iHigh(_Symbol, PERIOD_CURRENT, c) : iLow(_Symbol, PERIOD_CURRENT, c);",
            "   for(int i = shift; i <= shift + 2 * w; i++)",
            "   {",
            "      double x = wantHigh ? iHigh(_Symbol, PERIOD_CURRENT, i) : iLow(_Symbol, PERIOD_CURRENT, i);",
            "      if(wantHigh ? (x > v) : (x < v)) return false;",
            "   }",
            "   return true;",
            "}",
            "",
        ]
    if kinds & {"swing_bos", "swing_choch"}:
        lines += [
            "double T58SwingEvent(int w, int shift, int wantChoch)",
            "{",
            "   // Replays the fractal BOS/ChoCH detector (market_structure.",
            "   // calculate_hh_ll_structure: UNIQUE window extremes, HH/HL/LH/LL",
            "   // labels, event on the confirmation bar) over the most recent",
            "   // 800 bars ending at `shift`; lows processed before highs.",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   double lastHigh = 0.0, lastLow = 0.0;",
            "   bool hasHigh = false, hasLow = false;",
            "   int trend = 0;",
            "   double ev = 0.0;",
            "   for(int p = shift + 800; p >= shift + w; p--)",
            "   {",
            "      if(p + w >= total) continue;",
            "      double lv = iLow(_Symbol, PERIOD_CURRENT, p);",
            "      int cntL = 0; bool beatL = false;",
            "      for(int j = p - w; j <= p + w; j++)",
            "      {",
            "         double x = iLow(_Symbol, PERIOD_CURRENT, j);",
            "         if(x < lv) beatL = true;",
            "         if(x == lv) cntL++;",
            "      }",
            "      if(!beatL && cntL == 1)",
            "      {",
            "         if(!hasLow) { lastLow = lv; hasLow = true; }",
            "         else if(lv > lastLow) { if(trend != -1) trend = 1; lastLow = lv; }",
            "         else",
            "         {",
            "            if(p - w == shift) ev = (trend == 1) ? (wantChoch ? 1.0 : 0.0) : ((trend == -1) ? (wantChoch ? 0.0 : 1.0) : 0.0);",
            "            trend = -1;",
            "            lastLow = lv;",
            "         }",
            "      }",
            "      double hv = iHigh(_Symbol, PERIOD_CURRENT, p);",
            "      int cntH = 0; bool beatH = false;",
            "      for(int j = p - w; j <= p + w; j++)",
            "      {",
            "         double x = iHigh(_Symbol, PERIOD_CURRENT, j);",
            "         if(x > hv) beatH = true;",
            "         if(x == hv) cntH++;",
            "      }",
            "      if(!beatH && cntH == 1)",
            "      {",
            "         if(!hasHigh) { lastHigh = hv; hasHigh = true; }",
            "         else if(hv > lastHigh)",
            "         {",
            "            if(p - w == shift) ev = (trend == -1) ? (wantChoch ? 1.0 : 0.0) : ((trend == 1) ? (wantChoch ? 0.0 : 1.0) : 0.0);",
            "            trend = 1;",
            "            lastHigh = hv;",
            "         }",
            "         else { if(trend != 1) trend = -1; lastHigh = hv; }",
            "      }",
            "   }",
            "   return ev;",
            "}",
            "",
        ]
    if kinds & {"atr_regime", "atr_expansion", "atr_contraction"}:
        lines += [
            "double T58AtrRegime(int period, double expMult, double contMult, int shift)",
            "{",
            "   // Wilder ATR vs its trailing mean over max(3*period, period+1) bars:",
            "   // 1 = expansion, -1 = contraction, 0 = neutral (manual.py atr_regime).",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   int start = shift + period * 8 + 60;",
            "   if(start >= total - 1) start = total - 2;",
            "   if(start <= shift) return 0.0;",
            "   double atrs[];",
            "   ArrayResize(atrs, start - shift + 1);",
            "   int count = 0, seen = 0;",
            "   double atr = 0.0, seedSum = 0.0;",
            "   bool seeded = false;",
            "   for(int i = start; i >= shift; i--)",
            "   {",
            "      double h = iHigh(_Symbol, PERIOD_CURRENT, i);",
            "      double l = iLow(_Symbol, PERIOD_CURRENT, i);",
            "      double pc = iClose(_Symbol, PERIOD_CURRENT, i + 1);",
            "      double tr = MathMax(h - l, MathMax(MathAbs(h - pc), MathAbs(l - pc)));",
            "      seen++;",
            "      if(!seeded) { seedSum += tr; atr = seedSum / seen; if(seen >= period) seeded = true; }",
            "      else atr = (atr * (period - 1) + tr) / period;",
            "      atrs[count++] = atr;",
            "   }",
            "   int baseLen = MathMax(3 * period, period + 1);",
            "   int from = MathMax(0, count - baseLen);",
            "   double bSum = 0.0; int bN = 0;",
            "   for(int k = from; k < count; k++) { bSum += atrs[k]; bN++; }",
            "   double base = bN > 0 ? bSum / bN : 0.0;",
            "   if(base <= 0.0) return 0.0;",
            "   double cur = atrs[count - 1];",
            "   if(cur > base * expMult) return 1.0;",
            "   if(cur < base * contMult) return -1.0;",
            "   return 0.0;",
            "}",
            "",
        ]
    if "volatility_regime" in kinds:
        lines += [
            "double T58VolRegime(int period, double expMult, double contMult, int shift)",
            "{",
            "   // Rolling stdev of close returns vs its own trailing baseline,",
            "   // same 1 / -1 / 0 tristate as T58AtrRegime (manual.py volatility_regime).",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   int baseLen = MathMax(3 * period, period + 1);",
            "   int start = shift + baseLen + period + 5;",
            "   if(start >= total - 2) start = total - 3;",
            "   if(start <= shift) return 0.0;",
            "   double vols[];",
            "   ArrayResize(vols, start - shift + 1);",
            "   int count = 0;",
            "   for(int i = start; i >= shift; i--)",
            "   {",
            "      double rets[];",
            "      ArrayResize(rets, period);",
            "      double m = 0.0;",
            "      for(int k = 0; k < period; k++)",
            "      {",
            "         double c0 = iClose(_Symbol, PERIOD_CURRENT, i + k);",
            "         double c1 = iClose(_Symbol, PERIOD_CURRENT, i + k + 1);",
            "         rets[k] = (c1 != 0.0) ? (c0 / c1 - 1.0) : 0.0;",
            "         m += rets[k];",
            "      }",
            "      m /= period;",
            "      double v = 0.0;",
            "      for(int k = 0; k < period; k++) v += (rets[k] - m) * (rets[k] - m);",
            "      vols[count++] = (period > 1) ? MathSqrt(v / (period - 1)) : 0.0;",
            "   }",
            "   int from = MathMax(0, count - baseLen);",
            "   double bSum = 0.0; int bN = 0;",
            "   for(int k = from; k < count; k++) { bSum += vols[k]; bN++; }",
            "   double base = bN > 0 ? bSum / bN : 0.0;",
            "   if(base <= 0.0) return 0.0;",
            "   double cur = vols[count - 1];",
            "   if(cur > base * expMult) return 1.0;",
            "   if(cur < base * contMult) return -1.0;",
            "   return 0.0;",
            "}",
            "",
        ]
    if kinds & {"session_high", "session_low", "opening_range_high", "opening_range_low", "time_of_day", "day_of_week"}:
        lines += [
            "int T58MinutesOfDay(int shift)",
            "{",
            "   MqlDateTime dt;",
            "   TimeToStruct(iTime(_Symbol, PERIOD_CURRENT, shift), dt);",
            "   return dt.hour * 60 + dt.min;",
            "}",
            "",
        ]
    if kinds & {"session_high", "session_low", "opening_range_high", "opening_range_low"}:
        lines += [
            "int T58DayKey(int shift)",
            "{",
            "   MqlDateTime dt;",
            "   TimeToStruct(iTime(_Symbol, PERIOD_CURRENT, shift), dt);",
            "   return dt.year * 10000 + dt.mon * 100 + dt.day;",
            "}",
            "",
            "double T58SessionExtreme(int shift, int startMin, int endMin, bool wantHigh)",
            "{",
            "   // Session extreme so far today; before today's window opens, the",
            "   // previous day's final session value carries over (the engine's",
            "   // cummax-then-forward-fill). 0.0 when no session bars exist yet.",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   int evalDay = T58DayKey(shift);",
            "   double today = 0.0, prev = 0.0;",
            "   bool haveToday = false, havePrev = false;",
            "   int phase = 0, prevDayKey = 0;",
            "   for(int i = shift; i < total; i++)",
            "   {",
            "      int dk = T58DayKey(i);",
            "      if(dk != evalDay)",
            "      {",
            "         if(haveToday) break;",
            "         if(phase == 0) { phase = 1; prevDayKey = dk; }",
            "         else if(dk != prevDayKey) break;",
            "      }",
            "      int mins = T58MinutesOfDay(i);",
            "      if(mins < startMin || mins > endMin) continue;",
            "      double px = wantHigh ? iHigh(_Symbol, PERIOD_CURRENT, i) : iLow(_Symbol, PERIOD_CURRENT, i);",
            "      if(phase == 0) { today = haveToday ? (wantHigh ? MathMax(today, px) : MathMin(today, px)) : px; haveToday = true; }",
            "      else { prev = havePrev ? (wantHigh ? MathMax(prev, px) : MathMin(prev, px)) : px; havePrev = true; }",
            "   }",
            "   if(haveToday) return today;",
            "   return havePrev ? prev : 0.0;",
            "}",
            "",
            "double T58OpeningRange(int shift, int startMin, int endMin, bool wantHigh)",
            "{",
            "   // Full window extreme, visible only after the window closes (the",
            "   // engine fills forward from there); before that, yesterday's range.",
            "   int total = Bars(_Symbol, PERIOD_CURRENT);",
            "   int evalDay = T58DayKey(shift);",
            "   bool afterWindow = T58MinutesOfDay(shift) > endMin;",
            "   double today = 0.0, prev = 0.0;",
            "   bool haveToday = false, havePrev = false;",
            "   int phase = 0, prevDayKey = 0;",
            "   for(int i = shift; i < total; i++)",
            "   {",
            "      int dk = T58DayKey(i);",
            "      if(dk != evalDay)",
            "      {",
            "         if(phase == 0) { phase = 1; prevDayKey = dk; if(afterWindow && haveToday) break; }",
            "         else if(dk != prevDayKey) break;",
            "      }",
            "      int mins = T58MinutesOfDay(i);",
            "      if(mins < startMin || mins > endMin) continue;",
            "      double px = wantHigh ? iHigh(_Symbol, PERIOD_CURRENT, i) : iLow(_Symbol, PERIOD_CURRENT, i);",
            "      if(phase == 0) { today = haveToday ? (wantHigh ? MathMax(today, px) : MathMin(today, px)) : px; haveToday = true; }",
            "      else { prev = havePrev ? (wantHigh ? MathMax(prev, px) : MathMin(prev, px)) : px; havePrev = true; }",
            "   }",
            "   if(afterWindow && haveToday) return today;",
            "   return havePrev ? prev : 0.0;",
            "}",
            "",
        ]
    if "day_of_week" in kinds:
        lines += [
            "double T58DayOfWeek(int shift)",
            "{",
            "   // pandas convention: Monday = 0 .. Sunday = 6.",
            "   MqlDateTime dt;",
            "   TimeToStruct(iTime(_Symbol, PERIOD_CURRENT, shift), dt);",
            "   return (double)((dt.day_of_week + 6) % 7);",
            "}",
            "",
        ]
    return lines


def _mql5_render_condition(cond: _Condition, var_map: dict[tuple, str]) -> str:
    if cond.operator in ("crosses_above", "crosses_below"):
        left0, right0 = _mql5_render_scalar(cond.left, var_map, "0"), _mql5_render_scalar(cond.right, var_map, "0")
        left1, right1 = _mql5_render_scalar(cond.left, var_map, "1"), _mql5_render_scalar(cond.right, var_map, "1")
        if cond.operator == "crosses_above":
            return f"(({left0} > {right0}) && ({left1} <= {right1}))"
        return f"(({left0} < {right0}) && ({left1} >= {right1}))"
    if cond.operator == "is_true":
        return f"({_mql5_render_scalar(cond.left, var_map, '0')} != 0)"
    if cond.operator == "is_false":
        return f"({_mql5_render_scalar(cond.left, var_map, '0')} == 0)"
    left = _mql5_render_scalar(cond.left, var_map, "0")
    right = _mql5_render_scalar(cond.right, var_map, "0")
    return f"({left} {cond.operator} {right})"


def _mql5_render_group(group: _ConditionGroup, var_map: dict[tuple, str]) -> str:
    if not group.conditions:
        return "false"
    parts = [_mql5_render_condition(c, var_map) for c in group.conditions]
    expr = parts[0]
    for i, connector in enumerate(group.connectors):
        if i + 1 < len(parts):
            op = "&&" if connector == "AND" else "||"
            expr = f"({expr} {op} {parts[i + 1]})"
    return expr


def to_mql5(config: dict) -> str:
    """Renders a Manual Strategy Builder config as a standalone MQL5
    Expert Advisor, ready to compile in MetaEditor and attach to a live
    or demo MT5 account. Uses CTrade + handle/CopyBuffer indicators (the
    modern MQL5 idiom), not the legacy OrderSend() calling style."""
    if config.get("zone_entry"):
        return _zone_mql5(config)
    parsed = parse_manual_config(config)
    indicators = _collect_indicators(parsed)
    globals_, init_lines, tick_lines, var_map = _mql5_declare_indicators(indicators)

    # ATR-multiple stop/target need their own dedicated handle regardless of
    # whether the strategy's entry/exit conditions happen to reference an
    # ATR operand at the same period -- risk management is generated
    # independently of the condition expressions above.
    risk_atr_handles: dict[int, str] = {}
    for period in filter(None, [
        parsed.stop_atr_period if parsed.stop_type == "atr" else None,
        parsed.target_atr_period if parsed.target_type == "atr" else None,
        parsed.trailing_atr_period if parsed.trailing_enabled else None,
    ]):
        if period in risk_atr_handles:
            continue
        handle = f"h_risk_atr_{period}"
        arr = f"{handle}_buf"
        globals_.append(f"int {handle};")
        globals_.append(f"double {arr}[];")
        init_lines.append(f"{handle} = iATR(_Symbol, PERIOD_CURRENT, {period});")
        tick_lines.append(f"ArraySetAsSeries({arr}, true);")
        tick_lines.append(f"CopyBuffer({handle}, 0, 0, 3, {arr});")
        risk_atr_handles[period] = arr

    allow_long = parsed.direction in ("long", "both")
    allow_short = parsed.direction in ("short", "both")

    lines: list[str] = []
    lines.append("//+------------------------------------------------------------------+")
    lines.append(f"//| {parsed.name[:64]:<64} |")
    lines.append("//| Generated by the T58 Universal Strategy Translator from a Manual  |")
    lines.append("//| Strategy Builder config. Review before trading a live account.    |")
    lines.append("//+------------------------------------------------------------------+")
    lines.append("#include <Trade\\Trade.mqh>")
    lines.append("CTrade trade;")
    lines.append("")
    lines.append('input double LotSize = 0.10;')
    lines.append("")
    lines.extend(globals_)
    if parsed.max_bars_in_trade:
        lines.append(f"// T58_MAX_BARS_IN_TRADE={parsed.max_bars_in_trade}")
        lines.append("int barsInTrade = 0;")
    if parsed.trailing_enabled:
        # Trailing stop -- matches app.backtest.execution.py's own semantics:
        # T58_TRAIL_ATR_MULT is sampled ONCE at entry (not recalculated
        # every tick) and the stop only ever ratchets toward price (the
        # best high/low reached since entry, minus/plus that fixed
        # distance), never away from it.
        lines.append(f"// T58_TRAIL_ATR_MULT={_fmt_num(parsed.trailing_value)}")
        lines.append(f"// T58_TRAIL_ATR_PERIOD={parsed.trailing_atr_period}")
        lines.append("double g_trailDist = 0;")
        lines.append("double g_bestPrice = 0;")
    lines.append("")

    lines.append("int OnInit()")
    lines.append("{")
    lines.extend(f"   {line}" for line in init_lines)
    lines.append("   return(INIT_SUCCEEDED);")
    lines.append("}")
    lines.append("")

    lines.append("void OnTick()")
    lines.append("{")
    lines.append("   if (Bars(_Symbol, PERIOD_CURRENT) < 50) return; // let indicators warm up")
    lines.extend(f"   {line}" for line in tick_lines)
    lines.append("")
    long_entry_expr = _mql5_render_group(parsed.long_entry if allow_long else _ConditionGroup((), ()), var_map)
    short_entry_expr = _mql5_render_group(parsed.short_entry if allow_short else _ConditionGroup((), ()), var_map)
    long_exit_expr = _mql5_render_group(parsed.long_exit, var_map)
    short_exit_expr = _mql5_render_group(parsed.short_exit, var_map)

    lines.append(f"   bool longEntryCond = {long_entry_expr};")
    lines.append(f"   bool shortEntryCond = {short_entry_expr};")
    lines.append(f"   bool longExitCond = {long_exit_expr};")
    lines.append(f"   bool shortExitCond = {short_exit_expr};")
    lines.append("")

    if parsed.max_bars_in_trade:
        lines.append("   if (PositionSelect(_Symbol)) { barsInTrade++; } else { barsInTrade = 0; }")
        lines.append(f"   bool maxBarsExit = barsInTrade >= {parsed.max_bars_in_trade};")
        lines.append("   longExitCond = longExitCond || maxBarsExit;")
        lines.append("   shortExitCond = shortExitCond || maxBarsExit;")
        lines.append("")

    if parsed.time_exit:
        try:
            hh, mm = (int(x) for x in parsed.time_exit.split(":")[:2])
        except ValueError:
            raise TranslationError(f"Time-based exit '{parsed.time_exit}' must be in HH:MM format.")
        lines.append(f"   // T58_TIME_EXIT={parsed.time_exit}")
        lines.append("   MqlDateTime tm; TimeToStruct(TimeCurrent(), tm);")
        lines.append(f"   bool timeExitCond = (tm.hour > {hh}) || (tm.hour == {hh} && tm.min >= {mm});")
        lines.append("   longExitCond = longExitCond || timeExitCond;")
        lines.append("   shortExitCond = shortExitCond || timeExitCond;")
        lines.append("")

    lines.append("   if (PositionSelect(_Symbol))")
    lines.append("   {")
    lines.append("      long posType = PositionGetInteger(POSITION_TYPE);")
    if parsed.trailing_enabled:
        lines.append("      // Trailing stop: ratchet toward price, never away -- g_trailDist was")
        lines.append("      // captured once at entry below, not recalculated here.")
        lines.append("      if (posType == POSITION_TYPE_BUY)")
        lines.append("      {")
        lines.append("         double curHigh = iHigh(_Symbol, PERIOD_CURRENT, 0);")
        lines.append("         if (curHigh > g_bestPrice) g_bestPrice = curHigh;")
        lines.append("         double candidate = g_bestPrice - g_trailDist;")
        lines.append("         double curSL = PositionGetDouble(POSITION_SL);")
        lines.append("         if (curSL == 0 || candidate > curSL) trade.PositionModify(_Symbol, candidate, PositionGetDouble(POSITION_TP));")
        lines.append("      }")
        lines.append("      else if (posType == POSITION_TYPE_SELL)")
        lines.append("      {")
        lines.append("         double curLow = iLow(_Symbol, PERIOD_CURRENT, 0);")
        lines.append("         if (g_bestPrice == 0 || curLow < g_bestPrice) g_bestPrice = curLow;")
        lines.append("         double candidate = g_bestPrice + g_trailDist;")
        lines.append("         double curSL = PositionGetDouble(POSITION_SL);")
        lines.append("         if (curSL == 0 || candidate < curSL) trade.PositionModify(_Symbol, candidate, PositionGetDouble(POSITION_TP));")
        lines.append("      }")
    lines.append("      if (posType == POSITION_TYPE_BUY && longExitCond) trade.PositionClose(_Symbol);")
    lines.append("      if (posType == POSITION_TYPE_SELL && shortExitCond) trade.PositionClose(_Symbol);")
    lines.append("      return;")
    lines.append("   }")
    lines.append("")

    sl_tp_setup: list[str] = []
    if parsed.stop_type or parsed.target_type:
        sl_tp_setup.append('// T58_SL_PIPS / T58_SL_ATR_MULT below use the point size of THIS symbol.')
        if parsed.stop_type == "fixed":
            sl_tp_setup.append(f"   // T58_SL_PIPS={_fmt_num(parsed.stop_value)}")
            sl_tp_setup.append(f"   double slDist = {_fmt_num(parsed.stop_value)} * _Point;")
        elif parsed.stop_type == "atr":
            sl_tp_setup.append(f"   // T58_SL_ATR_MULT={_fmt_num(parsed.stop_value)}")
            sl_tp_setup.append(f"   // T58_ATR_PERIOD={parsed.stop_atr_period}")
            atr_expr = f"{risk_atr_handles[parsed.stop_atr_period]}[0]"
            sl_tp_setup.append(f"   double slDist = {atr_expr} * {_fmt_num(parsed.stop_value)};")
        if parsed.target_type == "fixed":
            sl_tp_setup.append(f"   // T58_TP_PIPS={_fmt_num(parsed.target_value)}")
            sl_tp_setup.append(f"   double tpDist = {_fmt_num(parsed.target_value)} * _Point;")
        elif parsed.target_type == "atr":
            sl_tp_setup.append(f"   // T58_TP_ATR_MULT={_fmt_num(parsed.target_value)}")
            sl_tp_setup.append(f"   // T58_ATR_PERIOD={parsed.target_atr_period}")
            atr_expr = f"{risk_atr_handles[parsed.target_atr_period]}[0]"
            sl_tp_setup.append(f"   double tpDist = {atr_expr} * {_fmt_num(parsed.target_value)};")

    lines.append("   double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);")
    lines.append("   double bid = SymbolInfoDouble(_Symbol, SYMBOL_BID);")
    lines.extend(sl_tp_setup)
    lines.append("")
    lines.append("   if (longEntryCond)")
    lines.append("   {")
    sl_long = "ask - slDist" if parsed.stop_type else "0"
    tp_long = "ask + tpDist" if parsed.target_type else "0"
    lines.append(f'      trade.Buy(LotSize, _Symbol, ask, {sl_long}, {tp_long});')
    if parsed.trailing_enabled:
        trail_atr_expr = f"{risk_atr_handles[parsed.trailing_atr_period]}[0]"
        lines.append(f"      g_trailDist = {trail_atr_expr} * {_fmt_num(parsed.trailing_value)};")
        lines.append("      g_bestPrice = ask;")
    lines.append("   }")
    lines.append("   else if (shortEntryCond)")
    lines.append("   {")
    sl_short = "bid + slDist" if parsed.stop_type else "0"
    tp_short = "bid - tpDist" if parsed.target_type else "0"
    lines.append(f'      trade.Sell(LotSize, _Symbol, bid, {sl_short}, {tp_short});')
    if parsed.trailing_enabled:
        trail_atr_expr = f"{risk_atr_handles[parsed.trailing_atr_period]}[0]"
        lines.append(f"      g_trailDist = {trail_atr_expr} * {_fmt_num(parsed.trailing_value)};")
        lines.append("      g_bestPrice = bid;")
    lines.append("   }")
    lines.append("}")
    lines.append("")
    if any(op.kind == "vwap" for op in indicators.values()):
        lines.append("// Session VWAP, matching app.strategy.indicators.vwap()'s own formula")
        lines.append("// exactly: cumulative (H+L+C)/3 * volume divided by cumulative volume,")
        lines.append("// reset at the start of each new day. Standard MQL5 has no built-in VWAP")
        lines.append("// indicator (unlike Pine's ta.vwap()), so this reproduces it directly from")
        lines.append("// historical rates rather than approximating with a moving average.")
        lines.append("double ComputeVWAP(int shift)")
        lines.append("{")
        lines.append("   MqlDateTime startDt;")
        lines.append("   TimeToStruct(iTime(_Symbol, PERIOD_CURRENT, shift), startDt);")
        lines.append("   double sumPV = 0.0, sumV = 0.0;")
        lines.append("   int total = Bars(_Symbol, PERIOD_CURRENT);")
        lines.append("   for (int i = shift; i < total; i++)")
        lines.append("   {")
        lines.append("      MqlDateTime dt;")
        lines.append("      TimeToStruct(iTime(_Symbol, PERIOD_CURRENT, i), dt);")
        lines.append("      if (dt.day != startDt.day || dt.mon != startDt.mon || dt.year != startDt.year) break;")
        lines.append("      double typical = (iHigh(_Symbol, PERIOD_CURRENT, i) + iLow(_Symbol, PERIOD_CURRENT, i) + iClose(_Symbol, PERIOD_CURRENT, i)) / 3.0;")
        lines.append("      double vol = (double)iVolume(_Symbol, PERIOD_CURRENT, i);")
        lines.append("      sumPV += typical * vol;")
        lines.append("      sumV += vol;")
        lines.append("   }")
        lines.append("   return sumV > 0.0 ? sumPV / sumV : 0.0;")
        lines.append("}")
        lines.append("")
    lines.extend(_mql5_helper_lines(indicators))
    lines.extend(_risk_todo_lines(parsed, "//"))
    lines.extend(_config_directive_lines(config, "//"))
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Round-trip config directive (embedded in every generated file so it can be
# translated onward later without re-deriving a config from the code) --
# see the module docstring's "ROUND-TRIP FIDELITY" section.
# ---------------------------------------------------------------------------

_CONFIG_DIRECTIVE_RE = re.compile(r"T58_MANUAL_CONFIG_JSON=(\{.*\})\s*$")


def _config_directive_lines(config: dict, comment_prefix: str) -> list[str]:
    try:
        payload = json.dumps(config, separators=(",", ":"), default=str)
    except (TypeError, ValueError):
        return []
    return [
        "",
        f"{comment_prefix} Full round-trip config below -- lets the T58 Universal Strategy",
        f"{comment_prefix} Translator convert this file to another language later without",
        f"{comment_prefix} re-deriving one from the code above by hand. Do not remove.",
        f"{comment_prefix} T58_MANUAL_CONFIG_JSON={payload}",
    ]


def _extract_embedded_config(source_text: str) -> dict | None:
    for line in source_text.splitlines():
        m = _CONFIG_DIRECTIVE_RE.search(line)
        if m:
            try:
                return json.loads(m.group(1))
            except (json.JSONDecodeError, ValueError):
                continue
    return None


# ---------------------------------------------------------------------------
# Config <-> structured-condition dict rendering (shared by every reverse
# parser below to build a Manual Strategy Builder config dict from the
# _Operand/_Condition/_ConditionGroup objects a symbolic parse produces)
# ---------------------------------------------------------------------------

def _operand_to_dict(op: _Operand):
    if op.kind == "constant":
        return op.value
    if op.kind == "price":
        return {"type": "price", "field": op.field}
    return {"type": op.kind, "field": op.field, "period": op.period}


_OPERATOR_DISPLAY = {"crosses_above": "crosses above", "crosses_below": "crosses below"}


def _condition_to_dict(cond: _Condition) -> dict:
    return {
        "left": _operand_to_dict(cond.left),
        "operator": _OPERATOR_DISPLAY.get(cond.operator, cond.operator),
        "right": _operand_to_dict(cond.right),
    }


def _group_to_dict_pair(group: _ConditionGroup) -> tuple[list[dict], list[str]]:
    return [_condition_to_dict(c) for c in group.conditions], list(group.connectors)


def _merge_groups_or(groups: list[_ConditionGroup]) -> _ConditionGroup:
    """Combines several condition groups with OR between each -- mirrors
    app.strategy.pinescript.PineScriptStrategy._combine /
    app.strategy.mql5.MQL5Strategy._combine's own "multiple entry
    statements for the same side are OR'd together" behavior, just
    symbolically instead of over an evaluated boolean Series.

    SAFE ONLY when at most one group has more than one internal
    condition: _ConditionGroup has no nested sub-groups, only one flat
    left-to-right chain (see _pine_render_group/_mql5_render_group/
    _python_render_group, none of which apply real AND-before-OR
    precedence) -- so naively flattening two multi-condition groups with
    OR between them would silently change which conditions bind
    together (e.g. "(a and b) or (c and d)" flattened to the chain
    "a and b or c and d" renders as "((a and b) or c) and d", NOT the
    original grouping). Raises TranslationError in that case rather than
    emit code that looks right and isn't -- the same posture as every
    other unsupported construct in this module."""
    groups = [g for g in groups if g.conditions]
    if not groups:
        return _ConditionGroup((), ())
    if len(groups) == 1:
        return groups[0]
    if sum(1 for g in groups if len(g.conditions) > 1) > 0:
        raise TranslationError(
            "Multiple entry/exit guards, each combining more than one condition, can't be safely "
            "OR'd together in the manual config format -- it has no parenthesized sub-groups, so "
            "flattening them would silently change which conditions bind together. Rewrite this as "
            "a single guard, or translate each guard as its own strategy."
        )
    conditions = tuple(g.conditions[0] for g in groups)
    connectors = tuple("OR" for _ in range(len(groups) - 1))
    return _ConditionGroup(conditions, connectors)


# ---------------------------------------------------------------------------
# Shared symbolic boolean-expression resolver -- used by both the
# PineScript and MQL5 reverse parsers below. Pine's native `and`/`or`
# keywords and MQL5's `&&`/`||` (converted to `and`/`or` by the MQL5
# parser before reaching here) feed the exact same resolver, since once
# normalized to "and"/"or" the two languages' boolean-condition subsets
# this module supports are identical: named-variable/price/constant
# operands compared with > >= < <= == !=, joined left-to-right by and/or.
# ---------------------------------------------------------------------------

_AND_OR_RE = re.compile(r"\s+(and|or)\s+", re.IGNORECASE)
_COMPARISON_OPS = (">=", "<=", "==", "!=", ">", "<")
_AVERAGED_PRICE_ALIASES = {"hl2", "hlc3", "ohlc4"}


def _fully_wrapped(expr: str) -> bool:
    """True if expr starts and ends with a SINGLE matching pair of
    parens wrapping the whole expression (not e.g. "(a) and (b)", which
    merely starts with '(' and ends with ')')."""
    if not (expr.startswith("(") and expr.endswith(")")):
        return False
    depth = 0
    for i, ch in enumerate(expr):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0 and i != len(expr) - 1:
                return False
    return depth == 0


def _split_top_level_bool(expr: str) -> tuple[list[str], list[str]]:
    """Splits `expr` into atomic terms and AND/OR connectors, only at
    paren-depth 0 -- exactly mirroring how left-to-right connectors chain
    in this module's own _ConditionGroup (see _pine_render_group /
    _mql5_render_group), which is why a plain left-to-right split (no
    real AND-before-OR precedence) round-trips correctly against this
    module's own renderers."""
    terms: list[str] = []
    connectors: list[str] = []
    depth = 0
    last = 0
    i = 0
    n = len(expr)
    while i < n:
        ch = expr[i]
        if ch == "(":
            depth += 1
            i += 1
            continue
        if ch == ")":
            depth -= 1
            i += 1
            continue
        if depth == 0:
            m = _AND_OR_RE.match(expr, i)
            if m:
                terms.append(expr[last:i].strip())
                connectors.append(m.group(1).upper())
                i = m.end()
                last = i
                continue
        i += 1
    terms.append(expr[last:].strip())
    return terms, connectors


def _split_comparison(expr: str) -> tuple[str, str, str] | None:
    for op in _COMPARISON_OPS:
        idx = expr.find(op)
        if idx > 0:
            return expr[:idx].strip(), op, expr[idx + len(op):].strip()
    return None


def _resolve_operand_token(token: str, var_defs: dict[str, _Operand]) -> _Operand:
    token = token.strip()
    try:
        return _Operand(kind="constant", value=float(token))
    except ValueError:
        pass
    if token in _PRICE_FIELDS:
        return _Operand(kind="price", field=token)
    if token in _AVERAGED_PRICE_ALIASES:
        raise TranslationError(
            f"'{token}' is an averaged price source (no single OHLC field backs it) with no "
            "equivalent operand in the manual config format -- rewrite the source using "
            "open/high/low/close directly, or translate a version of this strategy that already "
            "does."
        )
    if token in var_defs:
        return var_defs[token]
    raise TranslationError(f"Unsupported/unknown operand '{token}' for reverse translation.")


def _resolve_group(
    expr: str,
    var_defs: dict[str, _Operand],
    group_defs: dict[str, _ConditionGroup],
    cross_resolver=None,
) -> _ConditionGroup:
    expr = expr.strip()
    while _fully_wrapped(expr):
        expr = expr[1:-1].strip()
    if expr in group_defs:
        return group_defs[expr]
    if cross_resolver is not None:
        cross_group = cross_resolver(expr, var_defs)
        if cross_group is not None:
            return cross_group

    terms, connectors = _split_top_level_bool(expr)
    if len(terms) == 1:
        comp = _split_comparison(terms[0])
        if comp is None:
            raise TranslationError(f"Unsupported condition expression '{expr}' for reverse translation.")
        left_tok, op, right_tok = comp
        left = _resolve_operand_token(left_tok, var_defs)
        right = _resolve_operand_token(right_tok, var_defs)
        return _ConditionGroup((_Condition(left, _normalize_operator(op), right),), ())

    all_conditions: list = []
    all_connectors: list = []
    for idx, term in enumerate(terms):
        sub = _resolve_group(term, var_defs, group_defs, cross_resolver)
        if not sub.conditions:
            raise TranslationError(f"Empty condition term '{term}' for reverse translation.")
        if idx > 0:
            all_connectors.append(connectors[idx - 1])
        all_conditions.extend(sub.conditions)
        all_connectors.extend(sub.connectors)
    return _ConditionGroup(tuple(all_conditions), tuple(all_connectors))


def _config_from_groups(
    name: str,
    long_entry: _ConditionGroup, short_entry: _ConditionGroup,
    long_exit: _ConditionGroup, short_exit: _ConditionGroup,
    stop_loss_pips, take_profit_pips, sl_atr_mult, tp_atr_mult, atr_period,
) -> dict:
    if long_entry.conditions and short_entry.conditions:
        direction = "both"
    elif long_entry.conditions:
        direction = "long"
    else:
        direction = "short"

    long_conds, long_conns = _group_to_dict_pair(long_entry)
    short_conds, short_conns = _group_to_dict_pair(short_entry)
    lx_conds, lx_conns = _group_to_dict_pair(long_exit)
    sx_conds, sx_conns = _group_to_dict_pair(short_exit)

    config: dict = {
        "name": name,
        "market": {"direction": direction},
        "entry_conditions": {
            "long": long_conds, "long_connectors": long_conns,
            "short": short_conds, "short_connectors": short_conns,
        },
        "exit_conditions": {
            "long": lx_conds, "long_connectors": lx_conns,
            "short": sx_conds, "short_connectors": sx_conns,
        },
        "risk_management": {},
    }
    rm = config["risk_management"]
    if sl_atr_mult is not None:
        rm["stop_type"], rm["stop_value"], rm["stop_atr_period"] = "atr", sl_atr_mult, atr_period
    elif stop_loss_pips is not None:
        rm["stop_type"], rm["stop_value"] = "fixed", stop_loss_pips
    if tp_atr_mult is not None:
        rm["target_type"], rm["target_value"], rm["target_atr_period"] = "atr", tp_atr_mult, atr_period
    elif take_profit_pips is not None:
        rm["target_type"], rm["target_value"] = "fixed", take_profit_pips
    return config


# ---------------------------------------------------------------------------
# PineScript reverse parsing (PineScript -> Manual Strategy Builder config)
# ---------------------------------------------------------------------------

_PINE_ASSIGN_RE = re.compile(r"^\s*(?:var\s+)?([A-Za-z_]\w*)\s*=\s*(.+?)\s*$")
_PINE_TA_CALL_RE = re.compile(r"ta\.(sma|ema|wma|rsi|vwma)\s*\(\s*([^,()]+)\s*,\s*([^()]+)\s*\)")
_PINE_VWAP_CALL_RE = re.compile(r"ta\.vwap\s*\(\s*[^()]*\s*\)")
_PINE_CROSS_CALL_RE = re.compile(r"ta\.(crossover|crossunder)\s*\(\s*([^,()]+)\s*,\s*([^()]+)\s*\)")
_PINE_INPUT_RE = re.compile(r"input\.(?:int|float)\s*\(\s*([-\d.]+)")
_PINE_IF_RE = re.compile(r"^(\s*)if\s+(.+?)\s*$")
_PINE_ENTRY_RE = re.compile(
    r'strategy\.entry\s*\(\s*"([^"]*)"\s*,\s*strategy\.(long|short)\s*(?:,.*?when\s*=\s*(.+?))?\s*\)'
)
_PINE_CLOSE_RE = re.compile(r'strategy\.close\s*\(\s*"([^"]*)"\s*(?:,.*?when\s*=\s*(.+?))?\s*\)')
_PINE_SL_RE = re.compile(r"T58_SL_PIPS\s*=\s*([\d.]+)")
_PINE_TP_RE = re.compile(r"T58_TP_PIPS\s*=\s*([\d.]+)")
_PINE_SL_ATR_RE = re.compile(r"T58_SL_ATR_MULT\s*=\s*([\d.]+)")
_PINE_TP_ATR_RE = re.compile(r"T58_TP_ATR_MULT\s*=\s*([\d.]+)")
_PINE_ATR_PERIOD_RE = re.compile(r"T58_ATR_PERIOD\s*=\s*(\d+)")


def _pine_strip_comment(line: str) -> tuple[str, str]:
    in_str = False
    for i, ch in enumerate(line):
        if ch == '"':
            in_str = not in_str
        elif ch == "/" and not in_str and i + 1 < len(line) and line[i + 1] == "/":
            return line[:i], line[i:]
    return line, ""


def _pine_join_continuation_lines(raw_lines: list[str]) -> list[str]:
    joined: list[str] = []
    buffer: list[str] = []
    depth = 0
    for raw_line in raw_lines:
        code, _ = _pine_strip_comment(raw_line)
        buffer.append(raw_line)
        depth += code.count("(") - code.count(")")
        if depth <= 0 or len(buffer) >= 20:
            joined.append(" ".join(buffer) if len(buffer) > 1 else buffer[0])
            buffer = []
            depth = 0
    if buffer:
        joined.append(" ".join(buffer) if len(buffer) > 1 else buffer[0])
    return joined


def _pine_cross_resolver(expr: str, var_defs: dict[str, _Operand]):
    m = _PINE_CROSS_CALL_RE.match(expr)
    if not m or m.group(0) != expr:
        return None
    func, a_tok, b_tok = m.groups()
    left = _resolve_operand_token(a_tok, var_defs)
    right = _resolve_operand_token(b_tok, var_defs)
    op = "crosses_above" if func == "crossover" else "crosses_below"
    return _ConditionGroup((_Condition(left, op, right),), ())


def _pine_resolve_length(token: str, var_defs: dict[str, _Operand]) -> int:
    token = token.strip()
    try:
        return int(float(token))
    except ValueError:
        pass
    op = var_defs.get(token)
    if op is not None and op.kind == "constant":
        return int(op.value)
    raise TranslationError(f"PineScript: could not resolve length argument '{token}' to a number.")


def _parse_pinescript_from_code(source: str) -> dict:
    var_defs: dict[str, _Operand] = {}
    group_defs: dict[str, _ConditionGroup] = {}

    stop_loss_pips = take_profit_pips = None
    sl_atr_mult = tp_atr_mult = None
    atr_period = 14

    long_entry_groups: list[_ConditionGroup] = []
    short_entry_groups: list[_ConditionGroup] = []
    long_exit_groups: list[_ConditionGroup] = []
    short_exit_groups: list[_ConditionGroup] = []

    if_stack: list[tuple[int, _ConditionGroup]] = []

    for raw_line in _pine_join_continuation_lines(source.splitlines()):
        code, comment = _pine_strip_comment(raw_line)

        m = _PINE_SL_RE.search(comment)
        if m:
            stop_loss_pips = float(m.group(1))
        m = _PINE_TP_RE.search(comment)
        if m:
            take_profit_pips = float(m.group(1))
        m = _PINE_SL_ATR_RE.search(comment)
        if m:
            sl_atr_mult = float(m.group(1))
        m = _PINE_TP_ATR_RE.search(comment)
        if m:
            tp_atr_mult = float(m.group(1))
        m = _PINE_ATR_PERIOD_RE.search(comment)
        if m:
            atr_period = int(m.group(1))

        if not code.strip():
            continue

        indent = len(code) - len(code.lstrip(" "))
        while if_stack and indent <= if_stack[-1][0]:
            if_stack.pop()

        if_match = _PINE_IF_RE.match(code)
        if if_match:
            cond_indent = len(if_match.group(1))
            group = _resolve_group(if_match.group(2).strip(), var_defs, group_defs, _pine_cross_resolver)
            if_stack.append((cond_indent, group))
            continue

        assign_match = _PINE_ASSIGN_RE.match(code)
        if assign_match:
            var_name, rhs = assign_match.groups()

            input_match = _PINE_INPUT_RE.search(rhs)
            if input_match and rhs.strip().startswith("input."):
                var_defs[var_name] = _Operand(kind="constant", value=float(input_match.group(1)))
                continue

            cross_match = _PINE_CROSS_CALL_RE.search(rhs)
            if cross_match:
                func, a_tok, b_tok = cross_match.groups()
                left = _resolve_operand_token(a_tok, var_defs)
                right = _resolve_operand_token(b_tok, var_defs)
                op = "crosses_above" if func == "crossover" else "crosses_below"
                group_defs[var_name] = _ConditionGroup((_Condition(left, op, right),), ())
                continue

            vwap_match = _PINE_VWAP_CALL_RE.search(rhs)
            if vwap_match:
                # ta.vwap()'s argument is always an averaged/typical price
                # source (hlc3 in this tool's own output, sometimes close
                # in hand-written scripts) -- that's normal for VWAP
                # specifically and doesn't hit the "averaged price source"
                # rejection below, since VWAP's own manual-config operand
                # (see app.strategy.indicators.vwap) always uses (H+L+C)/3
                # regardless of what's written here.
                var_defs[var_name] = _Operand(kind="vwap", field="close", period=14)
                continue

            ta_match = _PINE_TA_CALL_RE.search(rhs)
            if ta_match:
                func, src_tok, len_tok = ta_match.groups()
                src_tok = src_tok.strip()
                if src_tok in _AVERAGED_PRICE_ALIASES:
                    raise TranslationError(
                        f"PineScript: '{func}' is computed from '{src_tok}', an averaged price source "
                        "with no equivalent single price field in the manual config format."
                    )
                if src_tok not in _PRICE_FIELDS:
                    raise TranslationError(
                        f"PineScript: '{func}({src_tok}, ...)' -- indicators computed from another "
                        "indicator's output (rather than a plain price field) aren't representable "
                        "in the manual config format."
                    )
                period = _pine_resolve_length(len_tok, var_defs)
                var_defs[var_name] = _Operand(kind=func, field=src_tok, period=period)
                continue

            if any(op in rhs for op in ("<", ">", "==", "!=", " and ", " or ")):
                group_defs[var_name] = _resolve_group(rhs.strip(), var_defs, group_defs, _pine_cross_resolver)
                continue

            if rhs.strip() in _PRICE_FIELDS:
                var_defs[var_name] = _Operand(kind="price", field=rhs.strip())
                continue
            if rhs.strip() in _AVERAGED_PRICE_ALIASES:
                raise TranslationError(
                    f"PineScript: '{var_name} = {rhs.strip()}' -- averaged price sources have no "
                    "equivalent single price field in the manual config format."
                )

            raise TranslationError(
                f"PineScript: unsupported expression '{var_name} = {rhs}' for reverse translation."
            )

        entry_match = _PINE_ENTRY_RE.search(code)
        if entry_match:
            _, direction, when_expr = entry_match.groups()
            group = _pine_condition_for_statement(when_expr, if_stack, var_defs, group_defs)
            (long_entry_groups if direction == "long" else short_entry_groups).append(group)
            continue

        close_match = _PINE_CLOSE_RE.search(code)
        if close_match:
            trade_id, when_expr = close_match.groups()
            group = _pine_condition_for_statement(when_expr, if_stack, var_defs, group_defs)
            tid = (trade_id or "").lower()
            if "short" in tid:
                short_exit_groups.append(group)
            elif "long" in tid:
                long_exit_groups.append(group)
            else:
                long_exit_groups.append(group)
                short_exit_groups.append(group)
            continue

        # anything else (plotting, alerts, the strategy() declaration header,
        # etc.) is silently ignored, same as the forward parser

    if not long_entry_groups and not short_entry_groups:
        raise TranslationError(
            "PineScript: no strategy.entry(...) call was found -- nothing to translate. This "
            "parser supports the same subset app/strategy/pinescript.py's backtest importer does."
        )

    config = _config_from_groups(
        "Translated PineScript Strategy",
        _merge_groups_or(long_entry_groups), _merge_groups_or(short_entry_groups),
        _merge_groups_or(long_exit_groups), _merge_groups_or(short_exit_groups),
        stop_loss_pips, take_profit_pips, sl_atr_mult, tp_atr_mult, atr_period,
    )
    return config


def _pine_condition_for_statement(when_expr, if_stack, var_defs, group_defs) -> _ConditionGroup:
    if when_expr:
        return _resolve_group(when_expr.strip(), var_defs, group_defs, _pine_cross_resolver)
    if if_stack:
        return if_stack[-1][1]
    raise TranslationError(
        "PineScript: a strategy.entry()/strategy.close() call has no when= condition and is not "
        "inside an `if` block -- cannot determine when it should trigger."
    )


def parse_pinescript(source: str) -> dict:
    """Reverse-parses PineScript v5 source (the same subset
    app.strategy.pinescript.PineScriptStrategy already backtests) back
    into a Manual Strategy Builder config dict, so it can be translated
    onward into Python or MQL5. Prefers this module's own embedded
    T58_MANUAL_CONFIG_JSON round-trip directive when present (see module
    docstring) for perfect fidelity; otherwise derives a config from the
    code itself, raising TranslationError on anything outside the
    supported subset rather than guessing."""
    embedded = _extract_embedded_config(source)
    if embedded is not None:
        return embedded
    return _parse_pinescript_from_code(source)


# ---------------------------------------------------------------------------
# MQL5 reverse parsing (MQL5 -> Manual Strategy Builder config)
# ---------------------------------------------------------------------------

_MQL5_ASSIGN_RE = re.compile(r"^\s*(?:double|int|bool)?\s*([A-Za-z_]\w*)\s*=\s*(.+?);\s*$")
_MQL5_IMA_RE = re.compile(r"iMA\s*\([^,]+,[^,]+,\s*([^,]+),[^,]+,\s*(MODE_\w+)\s*,[^)]*\)")
_MQL5_IRSI_RE = re.compile(r"iRSI\s*\([^,]+,[^,]+,\s*([^,]+),[^)]*\)")
_MQL5_IF_BLOCK_RE = re.compile(r"^(\s*)if\s*\((.+)\)\s*\{\s*$")
_MQL5_IF_INLINE_RE = re.compile(r"^(\s*)if\s*\((.+?)\)\s*([^\{].*);\s*$")
_MQL5_BARE_IF_RE = re.compile(r"^\s*if\s*\((.+)\)\s*$")
_MQL5_BUY_RE = re.compile(r"trade\.Buy\s*\(|OrderSend\s*\([^)]*(?:ORDER_TYPE_BUY|OP_BUY)")
_MQL5_SELL_RE = re.compile(r"trade\.Sell\s*\(|OrderSend\s*\([^)]*(?:ORDER_TYPE_SELL|OP_SELL)")
_MQL5_CLOSE_RE = re.compile(r"trade\.PositionClose\s*\(|OrderClose\s*\(")
_MQL5_LINE_COMMENT_RE = re.compile(r"//.*$")
_MQL5_BLOCK_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
_MQL5_MODE_TO_KIND = {"MODE_SMA": "sma", "MODE_EMA": "ema", "MODE_LWMA": "wma"}


def _mql5_bool_to_generic(expr: str) -> str:
    expr = re.sub(r"&&", " and ", expr)
    expr = re.sub(r"\|\|", " or ", expr)
    return expr.strip()


def _parse_mql5_from_code(source: str) -> dict:
    code = _MQL5_BLOCK_COMMENT_RE.sub("", source)

    var_defs: dict[str, _Operand] = {}
    group_defs: dict[str, _ConditionGroup] = {}

    stop_loss_pips = take_profit_pips = None
    sl_atr_mult = tp_atr_mult = None
    atr_period = 14

    long_entry_groups: list[_ConditionGroup] = []
    short_entry_groups: list[_ConditionGroup] = []
    exit_groups: list[_ConditionGroup] = []

    if_stack: list[tuple[int, _ConditionGroup]] = []
    brace_depth = 0
    pending_cond: _ConditionGroup | None = None

    def materialize(cond_raw: str) -> _ConditionGroup:
        return _resolve_group(_mql5_bool_to_generic(cond_raw), var_defs, group_defs)

    def active_guard():
        return if_stack[-1][1] if if_stack else None

    for raw_line in code.splitlines():
        no_comment = _MQL5_LINE_COMMENT_RE.sub("", raw_line)

        m = _PINE_SL_RE.search(raw_line)
        if m:
            stop_loss_pips = float(m.group(1))
        m = _PINE_TP_RE.search(raw_line)
        if m:
            take_profit_pips = float(m.group(1))
        m = _PINE_SL_ATR_RE.search(raw_line)
        if m:
            sl_atr_mult = float(m.group(1))
        m = _PINE_TP_ATR_RE.search(raw_line)
        if m:
            tp_atr_mult = float(m.group(1))
        m = _PINE_ATR_PERIOD_RE.search(raw_line)
        if m:
            atr_period = int(m.group(1))

        line = no_comment.strip()
        if not line:
            continue

        if pending_cond is not None:
            if line == "{":
                if_stack.append((brace_depth, pending_cond))
                brace_depth += 1
                pending_cond = None
                continue
            guard = pending_cond
            pending_cond = None
            if _MQL5_BUY_RE.search(line):
                long_entry_groups.append(guard)
            elif _MQL5_SELL_RE.search(line):
                short_entry_groups.append(guard)
            elif _MQL5_CLOSE_RE.search(line):
                exit_groups.append(guard)
            continue

        if "}" in line:
            for _ in range(line.count("}")):
                brace_depth = max(0, brace_depth - 1)
                if if_stack and brace_depth == if_stack[-1][0]:
                    if_stack.pop()
            remainder = line.replace("}", "").strip()
            if not remainder:
                continue
            line = remainder

        assign_match = _MQL5_ASSIGN_RE.match(line)
        if assign_match:
            var_name, rhs = assign_match.groups()

            ima_match = _MQL5_IMA_RE.search(rhs)
            if ima_match:
                period_tok, mode = ima_match.groups()
                try:
                    period = int(float(period_tok.strip()))
                except ValueError:
                    raise TranslationError(f"MQL5: could not resolve iMA period '{period_tok}'.")
                kind = _MQL5_MODE_TO_KIND.get(mode, "sma")
                var_defs[var_name] = _Operand(kind=kind, field="close", period=period)
                continue

            irsi_match = _MQL5_IRSI_RE.search(rhs)
            if irsi_match:
                period_tok = irsi_match.group(1)
                try:
                    period = int(float(period_tok.strip()))
                except ValueError:
                    raise TranslationError(f"MQL5: could not resolve iRSI period '{period_tok}'.")
                var_defs[var_name] = _Operand(kind="rsi", field="close", period=period)
                continue

            if any(op in rhs for op in ("<", ">", "==", "!=", "&&", "||")):
                group_defs[var_name] = _resolve_group(_mql5_bool_to_generic(rhs), var_defs, group_defs)
                continue

            try:
                var_defs[var_name] = _Operand(kind="constant", value=float(rhs.strip()))
                continue
            except ValueError:
                pass

            raise TranslationError(
                f"MQL5: unsupported expression assigned to '{var_name}': '{rhs}' for reverse translation. "
                "Supported: iMA(...) with MODE_SMA/MODE_EMA/MODE_LWMA, iRSI(...), boolean comparisons, "
                "and numeric literals."
            )

        block_match = _MQL5_IF_BLOCK_RE.match(line)
        if block_match:
            group = materialize(block_match.group(2))
            if_stack.append((brace_depth, group))
            brace_depth += 1
            continue

        inline_match = _MQL5_IF_INLINE_RE.match(line)
        if inline_match:
            group = materialize(inline_match.group(2))
            stmt = inline_match.group(3)
            if _MQL5_BUY_RE.search(stmt):
                long_entry_groups.append(group)
            elif _MQL5_SELL_RE.search(stmt):
                short_entry_groups.append(group)
            elif _MQL5_CLOSE_RE.search(stmt):
                exit_groups.append(group)
            continue

        bare_if_match = _MQL5_BARE_IF_RE.match(line)
        if bare_if_match:
            pending_cond = materialize(bare_if_match.group(1))
            continue

        if line == "{" or line.endswith("{"):
            brace_depth += 1
            continue

        guard = active_guard()
        if _MQL5_BUY_RE.search(line):
            if guard is None:
                raise TranslationError("MQL5: found a Buy/OrderSend(BUY) call not guarded by an `if` condition.")
            long_entry_groups.append(guard)
            continue
        if _MQL5_SELL_RE.search(line):
            if guard is None:
                raise TranslationError("MQL5: found a Sell/OrderSend(SELL) call not guarded by an `if` condition.")
            short_entry_groups.append(guard)
            continue
        if _MQL5_CLOSE_RE.search(line):
            if guard is not None:
                exit_groups.append(guard)
            continue

        # anything else (OnInit/OnTick declarations, bookkeeping, etc.) is
        # silently ignored, same as the forward parser

    if not long_entry_groups and not short_entry_groups:
        raise TranslationError(
            "MQL5: no Buy/Sell (trade.Buy/trade.Sell/OrderSend) call was found inside a recognizable "
            "`if` condition -- nothing to translate. This parser supports the same subset "
            "app/strategy/mql5.py's backtest importer does."
        )

    # This parser's MQL5 subset has no per-side (long vs short) exit
    # distinction -- every trade.PositionClose(...) guard applies to
    # whichever side is open, matching app.strategy.mql5.MQL5Strategy's
    # own "EXIT SCOPE LIMIT" (see that module's forward parser docstring).
    exit_group = _merge_groups_or(exit_groups)
    config = _config_from_groups(
        "Translated MQL5 Strategy",
        _merge_groups_or(long_entry_groups), _merge_groups_or(short_entry_groups),
        exit_group, exit_group,
        stop_loss_pips, take_profit_pips, sl_atr_mult, tp_atr_mult, atr_period,
    )
    return config


def parse_mql5(source: str) -> dict:
    """Reverse-parses MQL5 source (the same subset
    app.strategy.mql5.MQL5Strategy already backtests) back into a Manual
    Strategy Builder config dict. Prefers this module's own embedded
    T58_MANUAL_CONFIG_JSON round-trip directive when present (see module
    docstring); otherwise derives a config from the code, raising
    TranslationError on anything outside the supported subset."""
    embedded = _extract_embedded_config(source)
    if embedded is not None:
        return embedded
    return _parse_mql5_from_code(source)


