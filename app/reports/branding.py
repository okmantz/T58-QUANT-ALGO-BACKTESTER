"""T58 mark for every generated report: one small, quiet badge, added once, and only to HTML documents.

``brand(html)`` is idempotent (a page that already carries the mark is returned unchanged) and never raises, so wrapping a report writer
with it cannot break report generation. The mark is a fixed corner badge on screen and a thin footer line in print, so it never covers
report content.
"""
from __future__ import annotations

MARKER = "t58-report-mark"

_CSS = ("<style>.t58-report-mark{position:fixed;right:14px;bottom:12px;z-index:50;font:600 11px/1 system-ui,-apple-system,Segoe UI,sans-serif;"
        "letter-spacing:.14em;color:#7a8794;background:rgba(15,20,26,.55);border:1px solid rgba(122,135,148,.35);border-radius:6px;"
        "padding:5px 8px;text-decoration:none;backdrop-filter:blur(4px)}.t58-report-mark b{color:#2dd4bf;font-weight:700}"
        "@media print{.t58-report-mark{position:static;display:block;text-align:right;background:none;border:0;color:#666;margin-top:12px}}</style>")
_BADGE = '<div class="t58-report-mark" title="Generated by T58 Quant Algo Backtester"><b>T58</b> QUANT</div>'


def brand(html: str) -> str:
    try:
        if not isinstance(html, str) or MARKER in html or "<body" not in html.lower():
            return html
        low = html.lower()
        i = low.rfind("</body>")
        out = html[:i] + _BADGE + html[i:] if i >= 0 else html + _BADGE
        j = out.lower().find("</head>")
        return (out[:j] + _CSS + out[j:]) if j >= 0 else _CSS + out
    except Exception:  # noqa: BLE001
        return html


def brand_file(path) -> None:
    """Brand an HTML file already on disk (best effort)."""
    try:
        from pathlib import Path
        p = Path(path)
        s = p.read_text(encoding="utf-8")
        b = brand(s)
        if b != s:
            p.write_text(b, encoding="utf-8")
    except Exception:  # noqa: BLE001
        pass
