#!/usr/bin/env python3
"""One-command test runner.

    python scripts/run_tests.py             # FAST tier, parallel  (minutes)   <- use this before building
    python scripts/run_tests.py --full      # everything, parallel
    python scripts/run_tests.py --web       # just the web/dashboard tests
    python scripts/run_tests.py --refresh-slow   # re-time the whole suite and rewrite tests/slow_tests.txt

The fast tier skips tests tagged `slow` (tests/slow_tests.txt). Parallelism uses pytest-xdist
(`pip install pytest-xdist`); without it the runner falls back to a single process.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SLOW_LIST = ROOT / "tests" / "slow_tests.txt"
SLOW_SECONDS = 2.0   # a single test slower than this lands in the slow tier


def _xdist() -> list[str]:
    try:
        import xdist  # noqa: F401
        return ["-n", "auto"]
    except ImportError:
        print("(pytest-xdist not installed -- running in one process; `pip install pytest-xdist` to go ~3x faster)")
        return []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--full", action="store_true", help="run every test, slow ones included")
    ap.add_argument("--web", action="store_true", help="only tests/web")
    ap.add_argument("--refresh-slow", action="store_true", help="time the whole suite and rewrite tests/slow_tests.txt")
    ap.add_argument("extra", nargs="*", help="extra pytest arguments")
    a = ap.parse_args()

    base = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"]
    if a.refresh_slow:
        out = ROOT / "tests" / ".durations.txt"
        cmd = base + ["tests", "--durations=0", "-m", "slow or not slow", *_xdist()]
        with out.open("w", encoding="utf-8") as fh:
            rc = subprocess.call(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT)
        slow = set()
        for line in out.read_text(encoding="utf-8", errors="replace").splitlines():
            m = re.match(r"\s*([\d.]+)s (?:call|setup|teardown)\s+(\S+)", line)
            if m and float(m.group(1)) >= SLOW_SECONDS:
                slow.add(m.group(2).split("[", 1)[0])
        SLOW_LIST.write_text("# tests slower than %.0fs -- generated by scripts/run_tests.py --refresh-slow\n" % SLOW_SECONDS + "\n".join(sorted(slow)) + "\n", encoding="utf-8")
        out.unlink(missing_ok=True)
        print(f"wrote {SLOW_LIST} ({len(slow)} slow tests)")
        return rc

    cmd = base + (["tests/web"] if a.web else ["tests"]) + _xdist()
    if not a.full:
        cmd += ["-m", "not slow"]
    return subprocess.call(cmd + a.extra, cwd=ROOT)


if __name__ == "__main__":
    raise SystemExit(main())
