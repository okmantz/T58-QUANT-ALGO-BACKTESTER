#!/usr/bin/env python3
"""Expand the shipped Strategy Graveyard seed with MORE real, measured failures -- biased toward near-misses.

Same honesty rules as scripts/build_graveyard_seed.py: every row is a candidate from the app's own strategy families,
generated by app.search.strategy_space and backtested with the real engine (app.backtest.engine.run_backtest, non-zero
spread / slippage / commission) on an in-sample slice and a held-out out-of-sample slice of a bundled dataset. Nothing is
invented -- every number in a row's reason/strength/notes is a measured number from that run.

What is different from the original builder:
  * Quality filter. Deep-negative filler (strategies that simply lose money everywhere by a wide margin) is dropped.
    A row is only kept if it is a genuine near-miss: it was profitable in-sample then collapsed out-of-sample, or it was
    profitable on both halves but breached a prop-style drawdown limit, or its held-out profit factor sat inside the
    noise band, or it was profitable but too thin to trust, or it LOST only a little after costs while a zero-cost
    re-run shows a real gross edge that spread/slippage/commission ate.
  * Diversity caps. Per-family and per-(family, dataset) caps so one chatty family can't flood the graveyard.
  * Richer diagnosis. Each row also carries measured `strength`, `secondary_failure` and a rule-based
    `suggested_mutation` (what to try next), so the Graveyard page's "why did it fail / what to try" view is useful.
  * Additive. Existing seed rows are kept byte-for-byte; new rows are de-duplicated against them by candidate_id and
    by (instrument, timeframe, param_signature), which is what tests/search/test_graveyard_seed.py requires.

Scope of the claim (written into every row): "no usable edge on THIS dataset slice under THESE costs" -- not a proof the
idea can never work elsewhere. This is the same light screen the original seed used (one in-sample/held-out split with
costs), NOT the Full Pipeline (walk-forward + CPCV + Monte Carlo): these rows are cheap, honest rejections of ideas that
were close enough to be worth recording, so Search Lab / Forge don't re-spend compute on the same neighbourhoods.

Usage:
    python scripts/expand_graveyard_seed.py                  # add ~450 new rows (takes ~20-40 min on 2 cores)
    python scripts/expand_graveyard_seed.py --target 500
    python scripts/expand_graveyard_seed.py --quick          # tiny smoke run, writes nothing unless --write
    python scripts/expand_graveyard_seed.py --dry-run        # compute + report, do not modify the seed file
"""
from __future__ import annotations

import argparse
import json
import sys
import warnings
from collections import Counter, defaultdict
from multiprocessing import Pool
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
warnings.filterwarnings("ignore")

SEED = ROOT / "app" / "search" / "seed_data" / "graveyard_seed.jsonl"

# label, file, pip_size, spread_pips, slippage_pips, bars  (first six match scripts/build_graveyard_seed.py exactly)
DATASETS = [
    ("EURUSD/EURUSD60.csv", "data/raw/EURUSD/EURUSD60.csv", 0.0001, 0.8, 0.2, 30000),
    ("EURUSD/EURUSD240.csv", "data/raw/EURUSD/EURUSD240.csv", 0.0001, 0.8, 0.2, 12000),
    ("GBPUSD/GBPUSD60.csv", "data/raw/GBPUSD/GBPUSD60.csv", 0.0001, 1.0, 0.3, 30000),
    ("GBPUSD/GBPUSD240.csv", "data/raw/GBPUSD/GBPUSD240.csv", 0.0001, 1.0, 0.3, 12000),
    ("XAUUSD (GOLD)/XAUUSD60.csv", "data/raw/XAUUSD (GOLD)/XAUUSD60.csv", 0.1, 3.0, 1.0, 30000),
    ("XAUUSD (GOLD)/XAUUSD240.csv", "data/raw/XAUUSD (GOLD)/XAUUSD240.csv", 0.1, 3.0, 1.0, 12000),
    ("USDJPY/USDJPY60.csv", "data/raw/USDJPY/USDJPY60.csv", 0.01, 0.9, 0.3, 30000),
    ("USDJPY/USDJPY240.csv", "data/raw/USDJPY/USDJPY240.csv", 0.01, 0.9, 0.3, 12000),
]
COMMISSION_PER_TRADE = 3.0
ACCOUNT = 100_000.0
RISK_PCT = 0.5
MAX_DD_LIMIT_PCT = 10.0
MIN_TRADES = 30          # below this a result can't distinguish edge from luck
MAX_NEAR_DD_PCT = 35.0   # drawdown-breach rows must be within reach of a limit, not catastrophic
MIN_TRADES_FLOOR = 15    # below this a row is pure noise -> not worth recording at all
SEED_BASE = 5000         # distinct from the original builder's 1000+i so candidates differ

# near-miss gates for "lost money in both halves" rows (anything worse is filler and is dropped)
NEAR_PF_BEST = 0.92      # at least one half had PF >= this
NEAR_PF_OOS = 0.82       # and the held-out half was not a disaster


def _mutation(primary: str, family: str, ret_is: float, ret_oos: float, dd: float, gross_pf: float | None) -> str:
    if primary == "out-of-sample collapse":
        return ("Narrow the parameter grid and re-validate with Walk-Forward Optimization; the in-sample edge looks "
                "curve-fit, so require the best parameters to sit on a flat plateau (Parameter Sensitivity) before trusting it")
    if primary == "drawdown breach":
        return ("Edge survived costs on both halves but the path was too rough for a prop account: try halving risk per "
                "trade, adding a daily-loss circuit breaker, or a volatility/regime filter that sits out the worst stretch")
    if primary == "marginal edge":
        return ("Held-out PF is inside the noise band: add a higher-quality entry filter (session, volatility regime or "
                "higher-timeframe bias) to cut trade count and lift expectancy per trade")
    if primary == "too few trades":
        return ("Profitable but too thin to trust: loosen the entry trigger, widen the session window, or port it to a "
                "faster timeframe / more instruments until it clears 30+ trades")
    if gross_pf is not None and gross_pf >= 1.05:
        return ("A real gross edge exists before costs (zero-cost PF %.2f) but spread/slippage/commission eat it: raise "
                "the target/stop size, trade less often, or move to a longer timeframe so costs are a smaller fraction of "
                "each trade" % gross_pf)
    return ("Roughly break-even after costs: combine with a regime filter or use as one leg of an ensemble rather than "
            "standalone")


def _run(args):
    label, path, pip, spread, slip, bars, family, per_family, seed = args
    from app.backtest.engine import run_backtest
    from app.backtest.risk import RiskConfig
    from app.data.importer import import_csv
    from app.data.timeframe_resample import infer_timeframe_label
    from app.search.graveyard import param_signature
    from app.search.strategy_space import build_strategy_from_spec, generate_search_space

    try:
        df = import_csv(str(ROOT / path)).dataframe.tail(bars).reset_index(drop=True)
        tf = infer_timeframe_label(df)
        split = int(len(df) * 0.6)
        d_is, d_oos = df.iloc[:split].reset_index(drop=True), df.iloc[split:].reset_index(drop=True)
        t0, t1, t2 = (str(df["timestamp"].iloc[0])[:10], str(df["timestamp"].iloc[split])[:10],
                      str(df["timestamp"].iloc[-1])[:10])
    except Exception:  # noqa: BLE001
        return []
    risk = RiskConfig(initial_balance=ACCOUNT, risk_value=RISK_PCT, pip_size=pip, spread_pips=spread,
                      slippage_pips=slip, commission_per_trade=COMMISSION_PER_TRADE)
    free = RiskConfig(initial_balance=ACCOUNT, risk_value=RISK_PCT, pip_size=pip, spread_pips=0.0,
                      slippage_pips=0.0, commission_per_trade=0.0)
    try:
        space = generate_search_space("family", family=family, max_candidates=per_family, seed=seed)
    except Exception:  # noqa: BLE001
        return []
    rows = []
    for cid, spec in space.candidates.items():
        params = (space.meta.get(cid) or {}).get("params") or {}
        try:
            r_is = run_backtest(d_is, build_strategy_from_spec(spec), risk, lookahead_check="skip")
            r_oos = run_backtest(d_oos, build_strategy_from_spec(spec), risk, lookahead_check="skip")
            s_is, s_oos = r_is.statistics, r_oos.statistics
            if s_is is None or s_oos is None:
                continue
        except Exception:  # noqa: BLE001 -- a candidate the engine can't run is not a measured failure
            continue
        n_is, n_oos = int(s_is.total_trades), int(s_oos.total_trades)
        n_all = n_is + n_oos
        if n_all < MIN_TRADES_FLOOR:
            continue
        ret_is, ret_oos = float(s_is.return_pct), float(s_oos.return_pct)
        pf_is, pf_oos = float(s_is.profit_factor or 0), float(s_oos.profit_factor or 0)
        dd = max(float(s_is.max_drawdown_pct), float(s_oos.max_drawdown_pct))

        secondary = None
        if n_all < MIN_TRADES:
            if not (ret_is > 0 and ret_oos > 0):
                continue                                   # thin AND unprofitable = filler
            primary = "too few trades"
            reason = (f"Profitable on both halves ({ret_is:+.1f}% / {ret_oos:+.1f}%, PF {pf_is:.2f}/{pf_oos:.2f}) but only "
                      f"{n_all} trades across {t0} to {t2} -- too few to tell an edge from luck.")
            oos = "positive"
        elif ret_oos <= 0 and ret_is > 0:
            if pf_is < 1.0 or ret_is < 0.5:
                continue                                   # a rounding-error in-sample 'edge' isn't an overfit near-miss
            primary = "out-of-sample collapse"
            reason = (f"Profitable in-sample ({ret_is:+.1f}%, PF {pf_is:.2f}) but lost money on held-out data "
                      f"({ret_oos:+.1f}%, PF {pf_oos:.2f}) -- an overfit edge that did not carry forward.")
            oos = "negative"
        elif ret_oos <= 0 and ret_is <= 0:
            if max(pf_is, pf_oos) < NEAR_PF_BEST or pf_oos < NEAR_PF_OOS:
                continue                                   # deep-negative filler
            primary = "no edge after costs"
            reason = (f"Lost money in both halves but only just (in-sample {ret_is:+.1f}%, out-of-sample {ret_oos:+.1f}%; "
                      f"PF {pf_is:.2f}/{pf_oos:.2f}) once spread, slippage and commission were charged.")
            oos = "negative"
        elif ret_is <= 0:
            continue    # lost in-sample, won held-out: unstable/lucky, not a clean near-miss -> not recorded
        elif dd > MAX_DD_LIMIT_PCT:
            if dd > MAX_NEAR_DD_PCT:
                continue    # a 60-90% drawdown is nowhere near a prop-viable strategy -> filler
            primary = "drawdown breach"
            reason = (f"Profitable ({ret_is:+.1f}% / {ret_oos:+.1f}%) but max drawdown reached {dd:.1f}%, "
                      f"through a {MAX_DD_LIMIT_PCT:.0f}% prop-style limit.")
            oos = "positive"
        elif pf_oos < 1.1:
            primary = "marginal edge"
            reason = f"Held-out profit factor only {pf_oos:.2f} ({ret_oos:+.1f}%) -- inside the noise band after costs."
            oos = "positive"
        else:
            continue  # survived this simple screen -- not a graveyard row

        # secondary failure + zero-cost gross edge (cheap: one more run per kept candidate)
        gross_pf = None
        try:
            g_is = run_backtest(d_is, build_strategy_from_spec(spec), free, lookahead_check="skip").statistics
            g_oos = run_backtest(d_oos, build_strategy_from_spec(spec), free, lookahead_check="skip").statistics
            if g_is is not None and g_oos is not None:
                gross_pf = round(float(g_oos.profit_factor or 0), 2)
                gross_is = round(float(g_is.profit_factor or 0), 2)
        except Exception:  # noqa: BLE001
            gross_pf = None
        if primary != "drawdown breach" and dd > MAX_DD_LIMIT_PCT:
            secondary = f"drawdown {dd:.1f}% also through a {MAX_DD_LIMIT_PCT:.0f}% limit"
        elif primary != "too few trades" and n_all < 60:
            secondary = f"only {n_all} trades -- thin sample"
        if primary == "no edge after costs" and (gross_pf is None or gross_pf < 1.0):
            continue          # no gross edge either: a dead idea, not a near-miss -> filler, drop it

        strengths = []
        if ret_is > 0 and ret_oos > 0:
            strengths.append(f"profitable on both halves ({ret_is:+.1f}% / {ret_oos:+.1f}%)")
        elif ret_is > 0:
            strengths.append(f"in-sample PF {pf_is:.2f}")
        if gross_pf is not None and gross_pf >= 1.05 and primary == "no edge after costs":
            strengths.append(f"real gross edge before costs (zero-cost held-out PF {gross_pf:.2f})")
        if dd <= MAX_DD_LIMIT_PCT and primary not in ("drawdown breach",):
            strengths.append(f"drawdown contained ({dd:.1f}%)")
        strength = "; ".join(strengths) or None

        notes = [
            f"starter seed (expansion): measured with the T58 engine on {label} ({tf}), {t0} to {t2}; "
            f"in-sample {t0}-{t1}, held-out {t1}-{t2}",
            f"costs: spread {spread}p, slippage {slip}p, ${COMMISSION_PER_TRADE:g}/trade; {RISK_PCT}% risk on ${ACCOUNT:,.0f}",
            "claim is scoped to this dataset slice and these costs -- not a proof the idea can never work elsewhere",
            "screen: single in-sample/held-out split with costs (not the Full Pipeline: no walk-forward, CPCV or Monte Carlo)",
        ]
        if gross_pf is not None:
            notes.append(f"zero-cost re-run: held-out PF {gross_pf:.2f} (in-sample {gross_is:.2f}) -- shows how much of the "
                         f"result is the edge vs. what costs took")
        notes.append(f"params: {json.dumps(params, sort_keys=True, default=str)}")
        rows.append({
            "_seed_instrument": label, "_seed_timeframe": tf,
            "candidate_id": f"seed-{cid}-{tf}", "family": family, "generation": None,
            "stage_died": "not_ranked", "reason": reason, "oos_result": oos,
            "neighbor_robustness_pct": None, "monte_carlo_failure_pct": None, "prop_sim_pass_pct": None,
            "cpcv_oos_pass_pct": None, "pbo": None, "fitness_score": round(pf_oos, 3),
            "param_signature": param_signature(family, params),
            "notes": notes,
            "primary_failure": primary, "secondary_failure": secondary, "strength": strength,
            "weakness": f"{n_all} trades; max drawdown {dd:.1f}%",
            "suggested_mutation": _mutation(primary, family, ret_is, ret_oos, dd, gross_pf),
            "_tier_score": _near_score(primary, pf_is, pf_oos, ret_is, ret_oos, gross_pf, n_all),
        })
    return rows


def _near_score(primary, pf_is, pf_oos, ret_is, ret_oos, gross_pf, n_all) -> float:
    """Higher = closer to a real strategy (more 'almost there'). Used only to rank when trimming to the target."""
    base = {"drawdown breach": 3.0, "marginal edge": 3.0, "out-of-sample collapse": 2.5,
            "too few trades": 2.0, "no edge after costs": 1.0}.get(primary, 0.0)
    return round(base + min(pf_is, 2.0) * 0.3 + min(pf_oos, 2.0) * 0.5 + (min(gross_pf, 2.0) * 0.4 if gross_pf else 0.0), 3)


def _load_existing() -> tuple[list[str], set, set]:
    lines, ids, sigs = [], set(), set()
    if SEED.exists():
        for ln in SEED.read_text(encoding="utf-8").splitlines():
            if not ln.strip():
                continue
            lines.append(ln)
            r = json.loads(ln)
            ids.add((r["_seed_instrument"], r["_seed_timeframe"], r["candidate_id"]))
            sigs.add((r["_seed_instrument"], r["_seed_timeframe"], r["param_signature"]))
    return lines, ids, sigs


def expand(per_family: int, target: int, quick: bool, dry_run: bool, per_family_cap: int, per_cell_cap: int,
           pool_cache: str | None = None) -> int:
    from app.search.strategy_space import FAMILIES

    existing_lines, ids, sigs = _load_existing()
    have_by_family = Counter(json.loads(ln)["family"] for ln in existing_lines)
    fams = list(FAMILIES)
    datasets = DATASETS[:1] if quick else DATASETS
    if quick:
        fams = fams[:6]
    # 1h datasets are ~4x slower per candidate (30k bars) so they get fewer candidates than the 4h ones
    tasks = [(l, p, pip, sp, sl, b, f, per_family if l.endswith("240.csv") else max(2, per_family // 3), SEED_BASE + i)
             for i, f in enumerate(fams) for (l, p, pip, sp, sl, b) in datasets]
    cand, seen = [], set()
    with Pool(processes=2) as pool:
        for i, chunk in enumerate(pool.imap_unordered(_run, tasks, chunksize=1), 1):
            for r in chunk:
                k_id = (r["_seed_instrument"], r["_seed_timeframe"], r["candidate_id"])
                k_sig = (r["_seed_instrument"], r["_seed_timeframe"], r["param_signature"])
                if k_id in ids or k_sig in sigs or k_id in seen or k_sig in seen:
                    continue
                seen.add(k_id)
                seen.add(k_sig)
                cand.append(r)
            if i % 40 == 0:
                print(f"  {i}/{len(tasks)} tasks, {len(cand)} near-miss candidates", flush=True)

    if pool_cache:
        Path(pool_cache).write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in cand) + "\n", encoding="utf-8")
    # --- select: best near-misses first, subject to diversity caps. Families with fewer existing rows get priority.
    cand.sort(key=lambda r: (-r["_tier_score"], have_by_family[r["family"]], r["candidate_id"]))
    chosen, fam_n, cell_n = [], Counter(), Counter()
    by_type = defaultdict(list)
    for r in cand:
        by_type[r["primary_failure"]].append(r)
    # round-robin across failure types (each list already best-first) so the mix stays balanced
    queues = {k: list(v) for k, v in by_type.items()}
    while queues and not (target and len(chosen) >= target):
        for k in list(queues):
            q = queues[k]
            while q:
                r = q.pop(0)
                if fam_n[r["family"]] >= per_family_cap or cell_n[(r["family"], r["_seed_instrument"])] >= per_cell_cap:
                    continue
                chosen.append(r)
                fam_n[r["family"]] += 1
                cell_n[(r["family"], r["_seed_instrument"])] += 1
                break
            if not q:
                queues.pop(k, None)
            if target and len(chosen) >= target:
                break
    for r in chosen:
        r.pop("_tier_score", None)
    chosen.sort(key=lambda r: (r["_seed_instrument"], r["_seed_timeframe"], r["family"], r["candidate_id"]))

    print(f"candidates passing the near-miss screen: {len(cand)}; selected: {len(chosen)}")
    print("by failure type:", dict(Counter(r["primary_failure"] for r in chosen)))
    print("families covered (new rows):", len(fam_n), "| instruments:", dict(Counter(r["_seed_instrument"] for r in chosen)))
    if dry_run:
        return len(chosen)
    OUT_LINES = existing_lines + [json.dumps(r, ensure_ascii=False) for r in chosen]
    SEED.parent.mkdir(parents=True, exist_ok=True)
    SEED.write_text("\n".join(OUT_LINES) + "\n", encoding="utf-8")
    print(f"seed now has {len(OUT_LINES)} rows ({len(existing_lines)} existing + {len(chosen)} new) -> {SEED.relative_to(ROOT)}")
    return len(chosen)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--per-family", type=int, default=14, help="candidates generated per family per dataset")
    ap.add_argument("--target", type=int, default=500, help="stop selecting once this many new rows are chosen")
    ap.add_argument("--per-family-cap", type=int, default=16, help="max new rows from any one family")
    ap.add_argument("--per-cell-cap", type=int, default=4, help="max new rows per (family, dataset)")
    ap.add_argument("--pool-cache", default=None, help="write every near-miss candidate found to this jsonl")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    expand(a.per_family, a.target, a.quick, a.dry_run or a.quick, a.per_family_cap, a.per_cell_cap, a.pool_cache)
